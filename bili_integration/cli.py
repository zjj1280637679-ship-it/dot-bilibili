"""Single-call JSON stdin adapter for trusted hosts; NOT MCP or tool registration."""
import argparse
import json
import os
from pathlib import Path
import stat
import sys

from facade import HostProfile
from facade.adapter import ROOT, workflow
from facade.contracts import TOOL_DEFINITIONS, envelope
from .dispatcher import dispatch

MAX_REQUEST_BYTES = 8192


def _pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError('duplicate_key')
        result[key] = value
    return result


def decode(raw):
    if len(raw) > MAX_REQUEST_BYTES:
        raise ValueError('request_too_large')
    return json.loads(raw.decode('utf-8'), object_pairs_hook=_pairs,
                      parse_constant=lambda value: (_ for _ in ()).throw(ValueError('nonfinite')))


def load_profile(path):
    """Trusted configuration must be a private, regular, non-symlink file."""
    fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    with os.fdopen(fd, 'rb') as stream:
        info = os.fstat(stream.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_mode & 0o077:
            raise ValueError('private_profile_required')
        data = decode(stream.read(MAX_REQUEST_BYTES + 1))
    if (not isinstance(data, dict)
            or not {'db', 'spool', 'source_url', 'tab'} <= set(data)
            or set(data) - {'db', 'spool', 'source_url', 'tab', 'timeout'}
            or not all(isinstance(data[k], str) and data[k] for k in ('db', 'spool', 'source_url', 'tab'))):
        raise ValueError('invalid_host_profile')
    return HostProfile(**data)


def diagnostics():
    """Inspect installed assets only. No ledger/spool reads or writes."""
    assets = ['scripts/read_workflow.py', 'scripts/browser_host_exchange.py']
    available = all((ROOT / name).is_file() for name in assets)
    return dict(status='ready_for_host_binding' if available else 'installation_incomplete',
                runtime_assets_present=available,
                source_digest=workflow.source_digest() if available else None,
                browser_access='not_checked', native_tool_registration=False,
                requires_concurrent_supported_host=True,
                ledger_relocation_supported=False)


def instructions():
    """Locate reviewed docs/collectors, never execute them."""
    bundled = Path(__file__).resolve().parent / 'resources'
    sources = {
        'workflow_protocol': ('docs', 'read-workflow.md'),
        'capture_protocol': ('docs', 'host-capture-recipes.md'),
        'host_contract': ('docs', 'browser-host-contract.md'),
        'capture_recipe': ('scripts', 'host_capture_recipes.js'),
        'projection_recipe': ('scripts', 'host_projection_recipe.js'),
        'integration_guide': ('docs', 'installable-integration.md'),
    }
    resources = {key: str(bundled / name if bundled.is_dir() else ROOT / folder / name)
                 for key, (folder, name) in sources.items()}
    return dict(resources=resources, runtime_root=str(ROOT),
                profile_locator='BILI_HOST_PROFILE or --profile',
                profile_fields=['db', 'spool', 'source_url', 'tab', 'timeout (optional)'],
                obligations=['Keep existing ledger on its original absolute runtime_root.',
                             'Observe fresh source_url and tab using the supported host for each new call.',
                             'Persist complete intent and stable host invocation ID before call.',
                             'Concurrently service spool with supported browser tools and fixed recipes.',
                             'Unknown is not cancellation; reconcile before further platform operations.'],
                native_tool_registration=False)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=['schemas', 'diagnose', 'instructions', 'call'])
    parser.add_argument('--profile', default=os.environ.get('BILI_HOST_PROFILE'),
                        help='trusted private JSON file (0600); defaults to BILI_HOST_PROFILE')
    parser.add_argument('--invocation-id', help='durably saved host ID, never generated by this adapter')
    args = parser.parse_args(argv)
    if args.action == 'schemas':
        result = TOOL_DEFINITIONS
    elif args.action == 'instructions':
        result = instructions()
    elif args.action == 'diagnose':
        result = diagnostics()
    else:
        if not args.profile:
            parser.error('call requires --profile')
        try:
            profile = load_profile(args.profile)
        except (OSError, ValueError, TypeError, RecursionError):
            result = envelope(None, code='host_profile_unavailable', action='contact_host')
        else:
            try:
                request = decode(sys.stdin.buffer.read(MAX_REQUEST_BYTES + 1))
            except (ValueError, UnicodeError, RecursionError):
                result = envelope(None, code='invalid_arguments', action='correct_arguments')
            else:
                result = dispatch(request, profile=profile, invocation_id=args.invocation_id)
    print(json.dumps(result, ensure_ascii=True, allow_nan=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
